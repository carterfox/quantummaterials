function [grayImage, croppedImage, laserX, laserY] = findAndCropLaserRegion()

[grayImage, laserX, laserY] = locateLaserPoint();
sideLengthPixels = 400;
croppedImage = imcrop( ...
    grayImage, ...
    [(laserX - sideLengthPixels/2) ...
    (laserY - sideLengthPixels/2) ...
    sideLengthPixels ...
    sideLengthPixels]);

croppedImage = imadjust(croppedImage,[0.3 0.75],[]);

end

